import math

splits=int(0.8*len(tokens))
train=tokens[:splits]
test=tokens[splits:]

train=["<s>"]+train+["</s>"]
test=["<s>"]+test+["</s>"]

uni=Counter(train)
bi=Counter(ngrams(train,2))
tri=Counter(ngrams(train,3))

V=len(uni)
N=sum(uni.values())

def unigram_prob(w):
  return (uni[w]+1)/(N+V)

def bigram_prob(w1,w2):
  return(bi[(w1,w2)]+1)/(uni[w1]+V)

def trigram_prob(w1,w2,w3):
  return (tri[(w1,w2,w3)]+1)/(bi[(w1,w2)]+V)

def perplexity(test,n):
  p=1
  N=len(test)

  if n==1:
    for w in test:
      p*=unigram_prob(w)

  elif n==2:
    for w1,w2 in ngrams(test,2):
      p*=bigram_prob(w1,w2)

  elif n==3:
    for w1,w2,w3 in ngrams(test,3):
      p*=trigram_prob(w1,w2,w3)

  return pow(p,-1/N)

print("Unigram Perplexity:", perplexity(test, 1))
print("Bigram Perplexity:", perplexity(test, 2))
print("Trigram Perplexity:", perplexity(test, 3))

