def rule_based_tagger(words):
  tags=[]
  for w in words:
    if w in ['the','a','an']:
      tag='DT'
    elif w in ['in','on','over','under']:
      tag='IN'
    elif w.endswith("ing"):
      tag='VBG'
    elif w.endswith("ed"):
      tag='VBD'
    elif w.endswith('ly'):
      tag='RB'
    elif w.endswith(('ous','able','ful','ive')):
      tag='JJ'
    elif w[0].isupper():
      tag='NNP'
    else:
      tag='NN'

    tags.append((w,tag))
  return tags

