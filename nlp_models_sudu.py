import numpy as np
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, SimpleRNN, Dense

#corpus

tokenizer = Tokenizer()
tokenizer.fit_on_texts([corpus])
sequence = tokenizer.texts_to_sequences([corpus])[0]

X,y = [],[]
for i in range(1,len(sequence)):
  X.append(sequence[:i])
  y.append(sequence[i])

X = pad_sequences(X)
y = np.array(y)

model = Sequential([
    Embedding(input_dim=100,output_dim=10,input_length=X.shape[1]),
    SimpleRNN(10),
    Dense(100,activation='softmax')
])

model.compile(loss='sparse_categorical_crossentropy',optimizer='adam')
model.fit(X,y,epochs=50,verbose=0)

test_text = "natural language"
test_seq = tokenizer.texts_to_sequences([test_text])
test_seq = pad_sequences(test_seq, maxlen=X.shape[1])

prediction = model.predict(test_seq)
predicted_word = tokenizer.index_word[np.argmax(prediction)]

print("Next word: ",predicted_word)

