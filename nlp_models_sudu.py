bigrams  = Counter(ngrams(tokens, 2))
trigrams = Counter(ngrams(tokens, 3))

print("Top 5 Unigrams:", unigrams.most_common(5))
print("Top 5 Bigrams:",  bigrams.most_common(5))
print("Top 5 Trigrams:", trigrams.most_common(5))

def plot_wordcloud(freq, title):
    words = {' '.join(k): v for k, v in freq.items()}
    wc = WordCloud().generate_from_frequencies(words)
    plt.imshow(wc)
    plt.title(title)
    plt.axis('off')
    plt.show()

plot_wordcloud(unigrams, "Unigram")
plot_wordcloud(bigrams,  "Bigram")
plot_wordcloud(trigrams, "Trigram")

"""Perplexity"""

print("\n=== EXP 2: PERPLEXITY ===")

split = int(len(tokens) * 0.8)
train_tokens = tokens[:split]
test_tokens  = tokens[split:]

train_unigrams = Counter(ngrams(train_tokens, 1))
train_bigrams  = Counter(ngrams(train_tokens, 2))
train_trigrams = Counter(ngrams(train_tokens, 3))
vocab_size = len(set(train_tokens))

def unigram_prob(w):
    return (train_unigrams[w] + 1) / (len(train_tokens) + vocab_size)

def bigram_prob(w1, w2):
    return (train_bigrams[(w1, w2)] + 1) / (train_unigrams[w1] + vocab_size)

def trigram_prob(w1, w2, w3):
    return (train_trigrams[(w1, w2, w3)] + 1) / (train_bigrams[(w1, w2)] + vocab_size)

def perplexity(probs):
    N = len(probs)
    return 2 ** (-sum(math.log2(p) for p in probs) / N)

uni_probs = [unigram_prob(w) for w in test_tokens]
bi_probs  = [bigram_prob(test_tokens[i-1], test_tokens[i]) for i in range(1, len(test_tokens))]
tri_probs = [trigram_prob(test_tokens[i-2], test_tokens[i-1], test_tokens[i]) for i in range(2, len(test_tokens))]

print("Unigram  Perplexity:", perplexity(uni_probs))
print("Bigram   Perplexity:", perplexity(bi_probs))
print("Trigram  Perplexity:", perplexity(tri_probs))

