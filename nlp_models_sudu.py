def normalize(text):
  text = text.lower()
  text = re.sub(r'\d+','',text)
  text = re.sub(r'\s+',' ',text).strip()
  text = text.translate(str.maketrans('','',string.punctuation))
  return text

normalized = normalize(corpus)
tokens = word_tokenize(normalized)

