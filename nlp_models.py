"""Perplexity"""

unifreq = FreqDist(unigrams)
bifreq = FreqDist(bigrams)
trifreq = FreqDist(trigrams)
vocab_size = len(unifreq)
def uniprb(word):
  return (unifreq[(word,)]+1)/(len(train_set)+vocab_size)
def biprb(word):
  return (bifreq[word]+1) / (unifreq[(word[0],)]+vocab_size)
def triprb(word):
  return (trifreq[word]+1)/ (bifreq[word[:2]]+vocab_size)
def perplexity(test_set,n):
  logprb = 0
  N = 0
  testngrams = list(ngrams(test_set,n))
  for tg in testngrams:
     if n == 1:
       prb = uniprb(tg[0])
     elif n == 2:
       prb = biprb(tg)
     else:
       prb = triprb(tg)
     logprb += math.log(prb)
     N += 1
     return math.exp(-logprb/N)

unigram_perplexity = perplexity(test_set, 1)
