def rulebasedtag(words):
  tags =[]
  for word in words:
    w = word.lower()
    if w in ['the','an','a']: tag='DT'
    elif w in ['in','on','at','over','under','with']: tag ='IN'
    elif w.endswith('ing'): tag = 'VBG'
    elif w.endswith('ed'): tag = 'VBD'
    elif w.endswith('ly'): tag = 'RB'
    elif w.endswith(('ful','ive','ous','able')): tag = 'JJ'
    elif word[0].isupper(): tag = 'NNP'
    else: tag = 'NN'
    tags.append((word,tag))
  return tags

